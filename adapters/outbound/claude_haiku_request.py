CLAUDE_MODEL_NAME = "claude-sonnet-4-6"


class ClaudeHaikuRequest(ClaudeRequestPort):
    def __init__(self, token: str):
        self.client = anthropic.Anthropic(api_key=token)

    async def generate_technical_task_offer(self, video_format_code: str | None, reference_text: str) -> str | None:
        user_payload = (
            f"FORMAT_CODE:\n{(video_format_code or 'shorts').strip()}\n\n"
            f"REFERENCE_TASK:\n{reference_text.strip()}"
        )
        try:
            message = await asyncio.to_thread(
                self.client.messages.create,
                model=CLAUDE_MODEL_NAME,
                max_tokens=1200,
                temperature=0.0,
                system=TECHNICAL_TASK_APPROVE_PROMPT,
                thinking={"type": "disabled"},
                messages=[
                    {
                        "role": "user",
                        "content": [{"type": "text", "text": user_payload}],
                    }
                ],
            )
            answer_parts: list[str] = []
            for block in message.content:
                if getattr(block, "type", None) == "text":
                    text = getattr(block, "text", "")
                    if text:
                        answer_parts.append(text)
            answer = "".join(answer_parts).strip()
            return answer or None
        except Exception:
            return None

    async def request_anwser(self, message_entity: Message) -> Optional[AnwserDTO]:
        user_text = message_entity.text.strip()
        if not user_text:
            return None

        history_lines = [f"{index + 1}. {line}" for index, line in enumerate(message_entity.history)]
        history_block = "\n".join(history_lines) if history_lines else "empty"

        if message_entity.flow == "technical_task":
            system_prompt = f"{ANTI_TROLL_PROMPT}\n\n{TECHNICAL_TASK_SYSTEM_PROMPT}"
            user_payload = f"HISTORY:\n{history_block}\n\nCURRENT_MESSAGE:\n{user_text}"
        else:
            system_prompt = f"{ANTI_TROLL_PROMPT}\n\n{APPLICATION_SYSTEM_PROMPT}\n\n{APPLICATION_FORM_PROMPT}"
            user_payload = (
                f"HISTORY:\n{history_block}\n\n"
                f"CURRENT_MESSAGE:\n{user_text}\n\n"
                f"MANAGER_BUSY:\n{BUSY_TIME}"
            )

        try:
            temperature = 0.0 if message_entity.flow == "technical_task" else 0.2
            message = await asyncio.to_thread(
                self.client.messages.create,
                model=CLAUDE_MODEL_NAME,
                max_tokens=1500,
                temperature=temperature,
                system=system_prompt,
                thinking={"type": "disabled"},
                messages=[
                    {
                        "role": "user",
                        "content": [{"type": "text", "text": user_payload}],
                    }
                ],
            )
            answer_parts: list[str] = []
            for block in message.content:
                if getattr(block, "type", None) == "text":
                    text = getattr(block, "text", "")
                    if text:
                        answer_parts.append(text)
            answer = "".join(answer_parts).strip()
            return AnwserDTO(text=answer) if answer else None
        except Exception:
            return None
